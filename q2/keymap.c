// ============================================================
// 旋钮（Encoder）支持
// Q2 有 1 个旋钮，顺时针 / 逆时针分别映射到矩阵虚拟键位：
//   顺时针（CW） → R4 C8（实际键码由当前激活层决定）
//   逆时针（CCW）→ R4 C7
// 旋钮事件通过伪造 keyevent 注入 QMK 按键处理流水线，
// 使其与普通按键共享同一套层逻辑（无需单独判断层）。
// ============================================================
#if defined(ENCODER_ENABLE)

#define ENCODERS 1
static uint8_t  encoder_state[ENCODERS] = {0};
static keypos_t encoder_cw[ENCODERS]    = {{ 8, 4 }};
static keypos_t encoder_ccw[ENCODERS]  = {{ 7, 4 }};

void encoder_action_register(uint8_t index, bool clockwise) {
    keyevent_t encoder_event = (keyevent_t) {
        .key = clockwise ? encoder_cw[index] : encoder_ccw[index],
        .pressed = true,
        .time = (timer_read() | 1)
    };
    // bit0 = 逆时针标记，bit1 = 顺时针标记
    encoder_state[index] = (clockwise ^ 1) | (clockwise << 1);
    action_exec(encoder_event);
}

void encoder_action_unregister(void) {
    for (int index = 0; index < ENCODERS; ++index) {
        if (encoder_state[index]) {
            keyevent_t encoder_event = (keyevent_t) {
                .key = encoder_state[index] >> 1 ? encoder_cw[index] : encoder_ccw[index],
                .pressed = false,
                .time = (timer_read() | 1)
            };
            encoder_state[index] = 0;
            action_exec(encoder_event);
        }
    }
}

void matrix_scan_user(void) {
    encoder_action_unregister();
}

bool encoder_update_user(uint8_t index, bool clockwise) {
    encoder_action_register(index, clockwise);
    return false;
};

#endif

// ============================================================
// 自定义键码处理
// ============================================================
bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    switch (keycode) {
        case NEW_LINE:
            // 行尾换行：先跳到行尾，再按 Enter，常用于 IDE 插入新行
            if (record->event.pressed) {
                SEND_STRING(SS_TAP(X_END) SS_TAP(X_ENT));
            }
            return false;

        case KC_MISSION_CONTROL:
            // 0x29F 是 macOS Mission Control 的 HID Consumer 控制码
            if (record->event.pressed) {
                host_consumer_send(0x29F);
            } else {
                host_consumer_send(0);
            }
            return false;

        case KC_LAUNCHPAD:
            // 0x2A0 是 macOS Launchpad 的 HID Consumer 控制码
            if (record->event.pressed) {
                host_consumer_send(0x2A0);
            } else {
                host_consumer_send(0);
            }
            return false;

        case KC_TASK:
            // Windows 任务视图：Win + Tab
            if (record->event.pressed) {
                register_code(KC_LWIN);
                register_code(KC_TAB);
            } else {
                unregister_code(KC_LWIN);
                unregister_code(KC_TAB);
            }
            return false;

        case KC_FLXP:
            // Windows 文件管理器：Win + E
            if (record->event.pressed) {
                register_code(KC_LWIN);
                register_code(KC_E);
            } else {
                unregister_code(KC_LWIN);
                unregister_code(KC_E);
            }
            return false;

        default:
            return true;
    }
}

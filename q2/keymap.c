#include QMK_KEYBOARD_H

// ============================================================
// 层定义
// 共 8 层：Mac 和 Windows 各一套基础层 + 三个功能层
//   MAC_BASE / WIN_BASE : 默认打字层（通过键盘侧面拨片切换）
//   M_CAP   / W_CAP    : 按住 Caps Lock 激活，导航 + 编辑层
//   M_FN    / W_FN     : 按住右侧第一个 Fn 键激活，媒体 + RGB 控制层
//   M_DOT   / W_DOT    : 按住右侧第二个 Fn 键激活，F 键 + 缩放层
// ============================================================
enum layers{

    MAC_BASE,
    WIN_BASE,

    M_CAP,
    M_FN,
    M_DOT,

    W_CAP,
    W_FN,
    W_DOT
};

